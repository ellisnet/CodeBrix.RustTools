    [Fact]
    public void Generate_orders_every_layer_and_appends_extra_lines_last()
    {
        //Arrange
        var spec = new BuildImageSpec
        {
            BaseImage = "rust",
            Tag = "1.94",
            RustVersion = "stable",
            AptPackages = { "libasound2-dev", "cmake" },
            InstallClippyRustfmt = true,
            CrossTargets = { CrossTarget.AndroidX64, CrossTarget.WindowsX64Gnullvm, CrossTarget.LinuxArm64, CrossTarget.LinuxNative },
