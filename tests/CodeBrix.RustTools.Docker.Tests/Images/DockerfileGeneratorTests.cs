    private const string MacOSLayer = """
        # macOS (aarch64-apple-darwin, x86_64-apple-darwin), DEVELOPMENT AND TESTING ONLY: Rust's own Darwin standard
        # libraries, linked by rustup's rust-lld against a libSystem symbol stub that is derived right here from those
        # libraries, a probe program and the C math function names. Nothing from Apple is downloaded, copied or needed. The
        # binaries carry an ad-hoc linker signature and must not be distributed or used in production; any macOS build that
        # will be is made on a Mac (CodeBrix.RustTools can do it there, with Apple's toolchain under Apple's terms).
        RUN rustup target add aarch64-apple-darwin x86_64-apple-darwin && rustup component add llvm-tools
        RUN <<'CODEBRIX_MACOS_SYSROOT'
        set -eu
        export LC_ALL=C
        root=/opt/codebrix/macos-sysroot
        sysroot="$(rustc --print sysroot)"
        host="$(rustc -vV | sed -n 's/^host: //p')"
        nm="$sysroot/lib/rustlib/$host/bin/llvm-nm"
        lld="$sysroot/lib/rustlib/$host/bin/rust-lld"
        mkdir -p "$root/usr/lib" /opt/codebrix/bin
        ln -sf "$lld" /opt/codebrix/bin/rust-lld
        work=/tmp/codebrix-macos-sysroot
        rm -rf "$work"; mkdir -p "$work"
        cat > "$work/probe.rs" <<'CODEBRIX_MACOS_PROBE'
        // Probe compiled by CodeBrix.RustTools.Docker while deriving the macOS libSystem stub: every float and memory
        // operation that rustc inlines into the compiled crate and LLVM then lowers to a C library call. The symbols this
        // object leaves undefined join the stub, and the probe is what the closed-loop link at the end builds.
        use std::hint::black_box;
        fn main() {
            let x: f64 = black_box(1.5);
            let y: f64 = black_box(2.5);
            let n: i32 = black_box(3);
            let d = [x.powf(y), x.powi(n), x.exp(), x.exp2(), x.ln(), x.log2(), x.log10(), x.log(y), x.sin(), x.cos(), x.tan(),
                x.asin(), x.acos(), x.atan(), x.atan2(y), x.sinh(), x.cosh(), x.tanh(), x.asinh(), x.acosh(), x.atanh(),
                x.cbrt(), x.hypot(y), x.exp_m1(), x.ln_1p(), x.mul_add(y, x), x.floor(), x.ceil(), x.round(), x.round_ties_even(),
                x.trunc(), x.fract(), x % y, x.rem_euclid(y), x.div_euclid(y), x.sqrt(), x.abs(), x.signum(), x.copysign(y),
                x.min(y), x.max(y), x.recip(), 10f64.powf(x), 2f64.powf(x), x.sin_cos().0 + x.sin_cos().1, x.to_degrees(), x.to_radians()];
            let a: f32 = black_box(1.5);
            let b: f32 = black_box(2.5);
            let s = [a.powf(b), a.powi(n), a.exp(), a.exp2(), a.ln(), a.log2(), a.log10(), a.log(b), a.sin(), a.cos(), a.tan(),
                a.asin(), a.acos(), a.atan(), a.atan2(b), a.sinh(), a.cosh(), a.tanh(), a.asinh(), a.acosh(), a.atanh(),
                a.cbrt(), a.hypot(b), a.exp_m1(), a.ln_1p(), a.mul_add(b, a), a.floor(), a.ceil(), a.round(), a.round_ties_even(),
                a.trunc(), a.fract(), a % b, a.rem_euclid(b), a.div_euclid(b), a.sqrt(), a.abs(), a.signum(), a.copysign(b),
                a.min(b), a.max(b), a.recip(), 10f32.powf(a), 2f32.powf(a), a.sin_cos().0 + a.sin_cos().1, a.to_degrees(), a.to_radians()];
            let count = black_box(64usize);
            let mut pattern = vec![0u64; count];
            for e in pattern.iter_mut() { *e = 0x0102030405060708; }
            let mut words = vec![0u32; count];
            for e in words.iter_mut() { *e = 0x01020304; }
            println!("probe {} {} {} {}", d.iter().sum::<f64>(), s.iter().sum::<f32>(), black_box(&pattern)[1], black_box(&words)[1]);
        }
        CODEBRIX_MACOS_PROBE
        # 1. For each target: the symbols Rust's precompiled rlibs leave undefined, minus the ones they define, plus what
        #    the probe object needs (float and memory operations are inlined into the compiled crate and lowered by LLVM to
        #    C library calls there, so only a compiled program shows them). What remains is what the system library must
        #    provide. Linker-provided section bounds and the allocator shim rustc generates at link time are dropped. Then
        #    the ISO C math function names and the Darwin library calls LLVM can emit are added, so any crate reaches them.
        for triple in aarch64-apple-darwin x86_64-apple-darwin; do
          libdir="$sysroot/lib/rustlib/$triple/lib"
          : > "$work/undef-$triple"; : > "$work/def-$triple"
          for rlib in "$libdir"/*.rlib; do
            "$nm" --undefined-only --format=just-symbols "$rlib" >> "$work/undef-$triple" 2>/dev/null || true
            "$nm" --defined-only --extern-only --format=just-symbols "$rlib" >> "$work/def-$triple" 2>/dev/null || true
          done
          rustc --target "$triple" -O --emit=obj -o "$work/probe-$triple.o" "$work/probe.rs"
          "$nm" --undefined-only --format=just-symbols "$work/probe-$triple.o" >> "$work/undef-$triple"
          sort -u "$work/undef-$triple" -o "$work/undef-$triple"
          sort -u "$work/def-$triple" -o "$work/def-$triple"
          comm -23 "$work/undef-$triple" "$work/def-$triple" \
            | grep -v -E '^(__mh_execute_header|___dso_handle)$' \
            | grep -v -E '^(section|segment)\$(start|end)\$' \
            | grep -v -E '__rustc|___rust_(alloc|dealloc|realloc|alloc_zeroed|no_alloc_shim)' \
            > "$root/symbols-$triple.txt"
          printf '%s\n' \
            ___exp10 ___exp10f ___sincos_stret ___sincosf_stret _acos _acosf _acosh _acoshf _asin _asinf \
            _asinh _asinhf _atan _atan2 _atan2f _atanf _atanh _atanhf _cbrt _cbrtf \
            _ceil _ceilf _copysign _copysignf _cos _cosf _cosh _coshf _erf _erfc \
            _erfcf _erff _exp _exp2 _exp2f _expf _expm1 _expm1f _fabs _fabsf \
            _fdim _fdimf _floor _floorf _fma _fmaf _fmax _fmaxf _fmin _fminf \
            _fmod _fmodf _frexp _frexpf _hypot _hypotf _ilogb _ilogbf _ldexp _ldexpf \
            _lgamma _lgamma_r _lgammaf _lgammaf_r _llrint _llrintf _llround _llroundf _log _log10 \
            _log10f _log1p _log1pf _log2 _log2f _logb _logbf _logf _lrint _lrintf \
            _lround _lroundf _memset_pattern16 _memset_pattern4 _memset_pattern8 _modf _modff _nan _nanf _nearbyint \
            _nearbyintf _nextafter _nextafterf _pow _powf _remainder _remainderf _remquo _remquof _rint \
            _rintf _round _roundf _scalbn _scalbnf _sin _sinf _sinh _sinhf _sqrt \
            _sqrtf _tan _tanf _tanh _tanhf _tgamma _tgammaf _trunc _truncf \
            >> "$root/symbols-$triple.txt"
          sort -u "$root/symbols-$triple.txt" -o "$root/symbols-$triple.txt"
        done
        # 2. The stub: a TAPI text file naming the install name and the symbols, nothing else; libc, libm, libpthread
        #    and libdl are the same stub under the names rustc links with.
        write_stub() {
          a="$root/symbols-aarch64-apple-darwin.txt"; x="$root/symbols-x86_64-apple-darwin.txt"
          common="$(comm -12 "$a" "$x" | paste -sd, - | sed 's/,/, /g')"
          armonly="$(comm -23 "$a" "$x" | paste -sd, - | sed 's/,/, /g')"
          x64only="$(comm -13 "$a" "$x" | paste -sd, - | sed 's/,/, /g')"
          {
            echo '--- !tapi-tbd'
            echo 'tbd-version:     4'
            echo 'targets:         [ arm64-macos, x86_64-macos ]'
            echo "install-name:    '/usr/lib/libSystem.B.dylib'"
            echo 'current-version: 1'
            echo 'compatibility-version: 1'
            echo 'exports:'
            echo '  - targets:     [ arm64-macos, x86_64-macos ]'
            echo "    symbols:     [ $common ]"
            [ -n "$armonly" ] && { echo '  - targets:     [ arm64-macos ]'; echo "    symbols:     [ $armonly ]"; }
            [ -n "$x64only" ] && { echo '  - targets:     [ x86_64-macos ]'; echo "    symbols:     [ $x64only ]"; }
            echo '...'
          } > "$root/usr/lib/libSystem.tbd"
          for alias in libc libm libpthread libdl; do cp "$root/usr/lib/libSystem.tbd" "$root/usr/lib/$alias.tbd"; done
        }
        # 3. Close the loop: link the probe against the stub and add whatever the linker still reports as
        #    undefined (symbols that only appear at link time: dyld_stub_binder, __tlv_bootstrap, _memmove).
        for triple in aarch64-apple-darwin x86_64-apple-darwin; do
          round=0
          while :; do
            write_stub
            if SDKROOT="$root" rustc --target "$triple" -O -C linker="$lld" -C linker-flavor=ld64.lld -C link-arg=-S \
                 -o "$work/probe-$triple" "$work/probe.rs" > "$work/link-$triple.log" 2>&1; then break; fi
            missing="$(grep -o 'undefined symbol: [^ ]*' "$work/link-$triple.log" | awk '{print $3}' | sort -u)"
            round=$((round + 1))
            if [ -z "$missing" ] || [ "$round" -gt 6 ]; then echo "macOS sysroot: $triple does not link:"; cat "$work/link-$triple.log"; exit 1; fi
            printf '%s\n' "$missing" >> "$root/symbols-$triple.txt"
            sort -u "$root/symbols-$triple.txt" -o "$root/symbols-$triple.txt"
          done
        done
        write_stub
        {
          echo 'Generated by CodeBrix.RustTools.Docker when this image was built.'
          echo 'usr/lib/libSystem.tbd lists the symbol names Rust'"'"'s standard library imports from /usr/lib/libSystem.B.dylib,'
          echo 'derived from the rustup-installed Darwin targets of this image'"'"'s toolchain, plus the ISO C math functions and the'
          echo 'Darwin library calls LLVM emits for float and memory operations (names only); symbols-<triple>.txt are the lists.'
          echo 'Nothing in this folder comes from Apple. Binaries linked against it are for development and testing only'
          echo 'and must not be distributed or used in production.'
          echo "toolchain: $(rustc -vV | sed -n 's/^release: //p') ($(rustc -vV | sed -n 's/^commit-hash: //p'))"
        } > "$root/README.txt"
        rm -rf "$work"
        CODEBRIX_MACOS_SYSROOT
        """;

