    [Fact]
    public void MacOSStubSupplement_is_a_sorted_unique_list_of_c_symbol_names()
    {
        //Arrange
        var list = DockerfileGenerator.MacOSStubSupplement;

        //Assert
        list.Should().Equal(list.OrderBy(s => s, StringComparer.Ordinal).ToArray());
        list.Distinct(StringComparer.Ordinal).Count().Should().Be(list.Count);
        list.Should().OnlyContain(s => Regex.IsMatch(s, "^_[A-Za-z0-9_]+$"));
        list.Should().Contain("_pow").And.Contain("_powf").And.Contain("_log").And.Contain("_fmod").And.Contain("_fma")
            .And.Contain("_lgammaf_r").And.Contain("___sincos_stret").And.Contain("___exp10").And.Contain("_memset_pattern16");
        (list.Count >= 110).Should().BeTrue($"{list.Count} names");
    }

    [Fact]
    public void Generate_embeds_the_probe_program_and_every_supplement_symbol_in_the_macos_layer()
    {
        //Act
        var text = DockerfileGenerator.Generate(new BuildImageSpec { CrossTargets = { CrossTarget.MacOSArm64 } });

        //Assert
        text.Should().Contain("\ncat > \"$work/probe.rs\" <<'CODEBRIX_MACOS_PROBE'\n").And.Contain("\nCODEBRIX_MACOS_PROBE\n");
        foreach (var line in DockerfileGenerator.MacOSProbeProgram)
        {
            text.Should().Contain("\n" + line + "\n");
        }

        foreach (var symbol in DockerfileGenerator.MacOSStubSupplement)
        {
            text.Should().Contain(" " + symbol + " ");
        }

        text.Should().Contain("--emit=obj -o \"$work/probe-$triple.o\" \"$work/probe.rs\"").And.NotContain("hello.rs");
    }

    private static string Golden(params string[] parts)
    {
        var lines = new List<string>();
        foreach (var part in parts)
        {
            lines.Add(part.Replace("\r\n", "\n"));
        }

        return string.Join("\n", lines) + "\n";
    }

