//! Build script: generates `$OUT_DIR/generated.rs`, which both binaries `include!`.
//!
//! It emits:
//! * build metadata (package version, profile, target triple, build time as Unix seconds)
//! * a 256-entry CRC-32 (IEEE) lookup table computed at build time
//! * a `PLANETS` array parsed from `data/planets.txt`

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

fn crc32_table() -> [u32; 256] {
    let mut table = [0u32; 256];
    for (i, slot) in table.iter_mut().enumerate() {
        let mut c = i as u32;
        for _ in 0..8 {
            c = if c & 1 != 0 { 0xEDB8_8320 ^ (c >> 1) } else { c >> 1 };
        }
        *slot = c;
    }
    table
}

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("set by cargo");
    let out_dir = env::var("OUT_DIR").expect("set by cargo");
    let data_file = Path::new(&manifest_dir).join("data").join("planets.txt");

    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=data/planets.txt");

    let mut code = String::new();
    let built_at = SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
    writeln!(code, "// @generated by build.rs - do not edit").unwrap();
    writeln!(code, "pub const PKG_VERSION: &str = {:?};", env::var("CARGO_PKG_VERSION").unwrap()).unwrap();
    writeln!(code, "pub const BUILD_PROFILE: &str = {:?};", env::var("PROFILE").unwrap_or_default()).unwrap();
    writeln!(code, "pub const BUILD_TARGET: &str = {:?};", env::var("TARGET").unwrap_or_default()).unwrap();
    writeln!(code, "pub const BUILD_UNIX_TIME: u64 = {built_at};").unwrap();
    writeln!(code, "pub const VERSION_STRING: &str = {:?};",
        format!("{} {} ({} build for {})", env::var("CARGO_PKG_NAME").unwrap(), env::var("CARGO_PKG_VERSION").unwrap(),
            env::var("PROFILE").unwrap_or_default(), env::var("TARGET").unwrap_or_default())).unwrap();

    code.push_str("pub static CRC32_TABLE: [u32; 256] = [\n");
    for chunk in crc32_table().chunks(8) {
        let line: Vec<String> = chunk.iter().map(|v| format!("0x{v:08X}")).collect();
        writeln!(code, "    {},", line.join(", ")).unwrap();
    }
    code.push_str("];\n");

    let text = fs::read_to_string(&data_file).unwrap_or_else(|e| panic!("cannot read {}: {e}", data_file.display()));
    code.push_str("/// (name, mean radius km, orbital period days)\npub static PLANETS: &[(&str, f64, f64)] = &[\n");
    let mut count = 0;
    for (lineno, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let parts: Vec<&str> = line.split(',').map(str::trim).collect();
        let [name, radius, period] = parts[..] else {
            panic!("data/planets.txt line {}: expected 3 comma-separated fields", lineno + 1);
        };
        let radius: f64 = radius.parse().unwrap_or_else(|_| panic!("line {}: bad radius", lineno + 1));
        let period: f64 = period.parse().unwrap_or_else(|_| panic!("line {}: bad period", lineno + 1));
        writeln!(code, "    ({name:?}, {radius:?}, {period:?}),").unwrap();
        count += 1;
    }
    code.push_str("];\n");

    if count < 8 {
        println!("cargo::warning=data/planets.txt only lists {count} planets");
    }

    fs::write(Path::new(&out_dir).join("generated.rs"), code).expect("write generated.rs");
}
