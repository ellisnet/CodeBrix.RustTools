using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using CodeBrix.RustTools.CrateBuilder.Facade.Model;
using CodeBrix.RustTools.CrateBuilder.Facade.Planning.Model;

namespace CodeBrix.RustTools.CrateBuilder.Facade.Planning;

/// <summary>
/// Writes the novice-facing wrap report of a <see cref="MappingPlan"/>: what was wrapped (types
/// to dispose, value types, enums, functions with their managed signatures), what was NOT
/// wrapped with the reason and what to do, notes from the crate's own documentation, and
/// warnings - plain UTF-8 text with <c>\n</c> line endings - plus its JSON twin (the plan itself,
/// <see cref="MappingPlanJson"/>) for agents.
/// </summary>
internal static class WrapReportWriter
{
    /// <summary>The usual file name of the report.</summary>
    public const string DefaultFileName = "WRAP-REPORT.txt";

    private const string Indent = "  ";

    /// <summary>The path of the JSON twin of a report at <paramref name="reportPath"/>: the same
    /// path with the extension <c>.json</c> (<c>WRAP-REPORT.txt</c> -&gt;
    /// <c>WRAP-REPORT.json</c>; a path without an extension gets <c>.json</c> appended).</summary>
    public static string JsonPathFor(string reportPath) => Path.ChangeExtension(reportPath, ".json");

    /// <summary>Writes the report to <paramref name="path"/> and its JSON twin beside it
    /// (<see cref="JsonPathFor"/>); folders are created; UTF-8 without a byte order mark.</summary>
    public static void Write(MappingPlan plan, string path)
    {
        if (plan == null)
        {
            throw new ArgumentNullException(nameof(plan));
        }

        if (string.IsNullOrWhiteSpace(path))
        {
            throw new ArgumentException("A report path is required.", nameof(path));
        }

        var full = Path.GetFullPath(path);
        var folder = Path.GetDirectoryName(full);
        if (!string.IsNullOrEmpty(folder))
        {
            Directory.CreateDirectory(folder);
        }

        var encoding = new UTF8Encoding(false);
        File.WriteAllText(full, Render(plan), encoding);
        File.WriteAllText(JsonPathFor(full), MappingPlanJson.Serialize(plan), encoding);
    }

    /// <summary>The JSON twin's text.</summary>
    public static string RenderJson(MappingPlan plan) => MappingPlanJson.Serialize(plan);

    /// <summary>The report's text.</summary>
    public static string Render(MappingPlan plan)
    {
        if (plan == null)
        {
            throw new ArgumentNullException(nameof(plan));
        }

        var sb = new StringBuilder();
        var libClass = PlannerNames.Pascal(plan.LibName);
        var exception = libClass + "Exception";
        var userFunctions = plan.Functions.Where(f => f.Kind != FunctionKind.Release && f.Kind != FunctionKind.Destroy).ToList();

        var title = "WRAP REPORT: " + plan.CrateName;
        Line(sb, title);
        Line(sb, new string('=', title.Length));
        Line(sb, $"How the Rust library \"{plan.CrateName}\" was wrapped for .NET (namespace {plan.ManagedNamespace}, assembly {plan.ManagedAssemblyName}).");
        Line(sb, "Generated by CodeBrix.RustTools.CrateBuilder from the crate's public API; regenerate it rather than editing it.");
        Line(sb);

        Heading(sb, "SUMMARY");
        Line(sb, Indent + "How:               " + (plan.UpstreamIsCdylib
            ? "the crate already exports C functions; they are used as they are"
            : $"a C layer (\"{plan.FacadeCrateName}\") was generated over the crate's Rust API"));
        var typeCount = plan.Handles.Count + plan.Mirrors.Count + plan.Enums.Count;
        Line(sb, Indent + "Wrapped types:     " + Count(typeCount) + $" ({Count(plan.Handles.Count)} {Plural(plan.Handles.Count, "object", "objects")} to dispose, {Count(plan.Mirrors.Count)} value {Plural(plan.Mirrors.Count, "type", "types")}, {Count(plan.Enums.Count)} {Plural(plan.Enums.Count, "enum", "enums")})");
        Line(sb, Indent + "Wrapped functions: " + Count(userFunctions.Count));
        if (plan.Constants.Count > 0)
        {
            Line(sb, Indent + "Constants:         " + Count(plan.Constants.Count) + " (copied into " + libClass + " as C# const values)");
        }

        Line(sb, Indent + "Not wrapped:       " + Count(plan.Skipped.Count) + (plan.Skipped.Count > 0 ? " (see NOT WRAPPED below)" : string.Empty));
        Line(sb, Indent + "Hand-written:      " + Count(plan.Overrides.Count) + " override" + (plan.Overrides.Count == 1 ? string.Empty : "s"));
        Line(sb, Indent + "Notes from docs:   " + Count(plan.DocNotes.Count));
        Line(sb, Indent + "Warnings:          " + Count(plan.Warnings.Count));
        if (!plan.UpstreamIsCdylib)
        {
            Line(sb);
            Line(sb, $"Errors: every call can throw {exception} if the Rust code panics or an argument is");
            Line(sb, $"rejected; functions marked \"(can fail)\" also throw {exception} with the Rust error");
            Line(sb, "message when the Rust function returns an error. Strings cross as UTF-8.");
        }

        Line(sb);

        Heading(sb, "WRAPPED TYPES");
        if (typeCount == 0)
        {
            Line(sb, Indent + "(none)");
        }

        if (plan.Handles.Count > 0)
        {
            Line(sb, "Objects - each one holds native memory. Dispose it when you are done (call Dispose(), or");
            Line(sb, "create it in a `using` statement). One object must not be used from two threads at once.");
            foreach (var h in plan.Handles)
            {
                Line(sb, Indent + h.ManagedName + RustName(h.RustPath));
                Doc(sb, h.Doc);
            }

            Line(sb);
        }

        if (plan.Mirrors.Count > 0)
        {
            Line(sb, "Value types - copied by value, nothing to dispose:");
            foreach (var m in plan.Mirrors)
            {
                var fields = string.Join("; ", m.Fields.Select(f => f.Type.ManagedType + " " + f.ManagedName));
                Line(sb, Indent + m.ManagedName + " { " + fields + " }" + RustName(m.RustPath));
                Doc(sb, m.Doc);
            }

            Line(sb);
        }

        if (plan.Enums.Count > 0)
        {
            Line(sb, "Enums:");
            foreach (var e in plan.Enums)
            {
                var values = string.Join(", ", e.Variants.Select(v => v.ManagedName + " = " + v.Value.ToString(CultureInfo.InvariantCulture)));
                Line(sb, Indent + e.ManagedName + " { " + values + " }" + RustName(e.RustPath));
                Doc(sb, e.Doc);
            }

            Line(sb);
        }

        if (typeCount == 0)
        {
            Line(sb);
        }

        if (plan.Constants.Count > 0)
        {
            Heading(sb, "CONSTANTS");
            Line(sb, libClass + " (C# const values, copied from the Rust source):");
            foreach (var k in plan.Constants)
            {
                Line(sb, Indent + "const " + k.ManagedType + " " + k.ManagedName + " = " + k.ManagedLiteral + RustName(k.RustPath));
            }

            Line(sb);
        }

        Heading(sb, "WRAPPED FUNCTIONS");
        if (userFunctions.Count == 0)
        {
            Line(sb, Indent + "(none)");
            Line(sb);
        }

        var free = userFunctions.Where(f => f.Owner == null).ToList();
        if (free.Count > 0)
        {
            Line(sb, libClass + " (static functions):");
            foreach (var f in free)
            {
                FunctionLine(sb, f);
            }

            Line(sb);
        }

        foreach (var h in plan.Handles)
        {
            Line(sb, h.ManagedName + ":");
            foreach (var f in h.Methods.Where(m => m.Kind != FunctionKind.Destroy))
            {
                FunctionLine(sb, f);
            }

            Line(sb, Indent + "void Dispose()");
            Line(sb, Indent + Indent + "Frees the native object (generated). Call it once when you are done.");
            Line(sb);
        }

        Heading(sb, "NOT WRAPPED");
        if (plan.Skipped.Count == 0)
        {
            Line(sb, Indent + "(nothing - everything public was wrapped)");
            Line(sb);
        }
        else
        {
            Line(sb, "Each item below can still be reached by adding a FacadeOverride (hand-written Rust, and");
            Line(sb, "optionally C#) to your WrapPlan with the item's path as RustPath; a starting point is shown.");
            Line(sb);
            foreach (var s in plan.Skipped)
            {
                Line(sb, Indent + s.RustPath + " (" + s.Kind + ")");
                Wrapped(sb, "Why: it " + s.Reason, Indent + Indent, Indent + Indent + "     ");
                if (!string.IsNullOrEmpty(s.OverrideHint))
                {
                    Line(sb, Indent + Indent + "Starting point:");
                    foreach (var hint in s.OverrideHint.TrimEnd('\n').Split('\n'))
                    {
                        Line(sb, Indent + Indent + Indent + hint);
                    }
                }

                Line(sb);
            }
        }

        Heading(sb, "NOTES FROM THE CRATE'S OWN DOCUMENTATION");
        if (plan.DocNotes.Count == 0)
        {
            Line(sb, Indent + "(none found)");
        }
        else
        {
            Line(sb, "Sentences that mention units, ranges, conventions or rules - check them before you call:");
            foreach (var n in plan.DocNotes)
            {
                Wrapped(sb, n.RustPath + ": " + n.Text, Indent, Indent + "    ");
            }
        }

        Line(sb);

        Heading(sb, "WARNINGS");
        if (plan.Warnings.Count == 0)
        {
            Line(sb, Indent + "(none)");
        }
        else
        {
            foreach (var w in plan.Warnings)
            {
                Wrapped(sb, "- " + w, Indent, Indent + "  ");
            }
        }

        if (plan.Overrides.Count > 0)
        {
            Line(sb);
            Heading(sb, "HAND-WRITTEN OVERRIDES");
            foreach (var o in plan.Overrides)
            {
                var rust = !string.IsNullOrWhiteSpace(o.RustSource);
                var csharp = !string.IsNullOrWhiteSpace(o.CSharpSource);
                Line(sb, Indent + o.RustPath + (rust && csharp ? " (Rust and C# source)" : rust ? " (Rust source)" : csharp ? " (C# source)" : " (no source)"));
            }
        }

        if (!string.IsNullOrWhiteSpace(plan.WrapPlanNotes))
        {
            Line(sb);
            Heading(sb, "YOUR WRAPPLAN NOTES");
            foreach (var line in plan.WrapPlanNotes.Replace("\r\n", "\n").TrimEnd('\n').Split('\n'))
            {
                Line(sb, Indent + line);
            }
        }

        return sb.ToString();
    }

    /// <summary>The managed signature of a function as the report shows it
    /// (<c>static uint Checksum(ReadOnlySpan&lt;byte&gt; data)</c>).</summary>
    public static string ManagedSignature(ExportedFunction f)
    {
        var parameters = new List<string>();
        var groups = f.Parameters.Where(p => p.RustName != "return").GroupBy(p => p.RustName, StringComparer.Ordinal);
        foreach (var group in groups)
        {
            var list = group.ToList();
            if (group.Key == "self" && list[0].Role == ParameterRole.Handle && f.Owner != null)
            {
                continue;
            }

            var main = list.FirstOrDefault(p => p.Role is ParameterRole.Value or ParameterRole.Handle or ParameterRole.SliceData or ParameterRole.StringData) ?? list[0];
            var type = main.Role == ParameterRole.StringData ? "string" : main.Type.ManagedType;
            if (list.Any(p => p.Role == ParameterRole.InPresent) && main.Role == ParameterRole.Value)
            {
                type += "?";
            }

            parameters.Add(type + " " + main.ManagedName);
        }

        var isStatic = f.Owner == null || f.Kind == FunctionKind.Constructor;
        return (isStatic ? "static " : string.Empty) + ReturnText(f.Return) + " " + f.ManagedName + "(" + string.Join(", ", parameters) + ")";
    }

    private static string ReturnText(ReturnMapping r)
    {
        if (r == null)
        {
            return "void";
        }

        switch (r.Shape)
        {
            case ReturnShape.Void:
            case ReturnShape.ResultVoid:
                return "void";
            case ReturnShape.Tuple:
            case ReturnShape.ResultTuple:
                return "(" + string.Join(", ", r.TupleItems.Select(t => t.ManagedType)) + ")";
            case ReturnShape.OptionalValue:
                return r.Type.ManagedType + (r.Type.Kind is MappingKind.Primitive or MappingKind.Bool or MappingKind.Enum or MappingKind.MirrorStruct or MappingKind.FixedArray ? "?" : string.Empty);
            default:
                return r.Type?.ManagedType ?? "void";
        }
    }

    private static bool CanFail(ReturnMapping r)
        => r != null && r.Shape is ReturnShape.ResultValue or ReturnShape.ResultHandle or ReturnShape.ResultVoid or ReturnShape.ResultBuffer or ReturnShape.ResultString or ReturnShape.ResultTuple;

    private static void FunctionLine(StringBuilder sb, ExportedFunction f)
    {
        var notes = new List<string>();
        if (CanFail(f.Return))
        {
            notes.Add("can fail");
        }

        if (f.Return != null && (f.Return.Shape is ReturnShape.OptionalValue or ReturnShape.OptionalHandle))
        {
            notes.Add("null when there is no result");
        }

        if (f.Kind == FunctionKind.ConsumingMethod)
        {
            notes.Add("uses the object up: afterwards only Dispose() may be called");
        }

        if (f.Return != null && (f.Return.Shape is ReturnShape.Handle or ReturnShape.ResultHandle or ReturnShape.OptionalHandle))
        {
            notes.Add("returns a new object you must dispose");
        }

        Line(sb, Indent + ManagedSignature(f) + (notes.Count > 0 ? "   (" + string.Join("; ", notes) + ")" : string.Empty));
        var summary = RustDocText.Summary(f.Doc);
        var origin = f.Kind == FunctionKind.PassThrough ? "C export " + f.CName : "Rust: " + f.RustPath;
        if (f.Kind == FunctionKind.Constructor && string.IsNullOrEmpty(f.Doc) && f.RustPath.EndsWith("::default", StringComparison.Ordinal))
        {
            summary = "Creates the default value (generated from the type's Default).";
        }
        else if (f.Kind == FunctionKind.Method && string.IsNullOrEmpty(f.Doc) && f.RustPath.EndsWith("::clone", StringComparison.Ordinal))
        {
            summary = "Creates an independent copy (generated from the type's Clone).";
        }

        Wrapped(sb, origin + "." + (summary.Length > 0 ? " " + summary : string.Empty), Indent + Indent);
    }

    private static string RustName(string rustPath) => "   (Rust: " + rustPath + ")";

    private static void Doc(StringBuilder sb, string doc)
    {
        var summary = RustDocText.Summary(doc);
        if (summary.Length > 0)
        {
            Wrapped(sb, summary, Indent + Indent);
        }
    }

    private static void Heading(StringBuilder sb, string text)
    {
        Line(sb, text);
        Line(sb, new string('-', text.Length));
    }

    private static void Wrapped(StringBuilder sb, string text, string indent, string continuation = null)
    {
        const int width = 96;
        var line = new StringBuilder();
        var first = true;
        foreach (var word in text.Replace("\r\n", "\n").Replace('\n', ' ').Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (line.Length > 0 && indent.Length + line.Length + 1 + word.Length > width)
            {
                Line(sb, indent + line);
                line.Clear();
                if (first)
                {
                    first = false;
                    indent = continuation ?? indent;
                }
            }

            if (line.Length > 0)
            {
                line.Append(' ');
            }

            line.Append(word);
        }

        if (line.Length > 0)
        {
            Line(sb, indent + line);
        }
    }

    private static string Count(int n) => n.ToString(CultureInfo.InvariantCulture);

    private static string Plural(int n, string one, string many) => n == 1 ? one : many;

    private static void Line(StringBuilder sb, string text = "") => sb.Append(text).Append('\n');
}
